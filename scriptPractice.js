// === toggle favorite ===
function toggleFavorite(qTitle, starElement) {
  const index = favoriteQuestions.indexOf(qTitle);

  if (index !== -1) {
    favoriteQuestions.splice(index, 1);
    starElement.classList.remove("active");
    starElement.textContent = "☆";
  } else {
    favoriteQuestions.push(qTitle);
    starElement.classList.add("active");
    starElement.textContent = "★";
  }

  // Save to Firebase if logged in :)
  if (currentUser) {
    const userRef = ref(database, "users/" + currentUser.uid);
    update(userRef, { favorites: favoriteQuestions });
  }
}

