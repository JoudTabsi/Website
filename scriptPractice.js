// === Show Single Question ===
function showQuestion(index) {
  document.getElementById("filter-container").style.display = "none";
  list.style.display = "none";
  homeBtnQuestions.style.display = "none";

  const q = currentQuestions[index];
  qText.innerHTML = "";
  choicesDiv.innerHTML = "";
  feedback.textContent = "";
  details.style.display = "none";
  details.innerHTML = "";
  explainSection.innerHTML = "";
  nextBtn.style.display = "none";

  // Favorite star inside question screen AAAAAAAAAAgh :(
  const star = document.createElement("span");
  star.className = "star-btn";
  star.textContent = favoriteQuestions.includes(q.title) ? "★" : "☆";
  if (favoriteQuestions.includes(q.title)) star.classList.add("active");
  star.style.cursor = "pointer";
  star.style.fontSize = "28px";
  star.style.float = "left";
  star.addEventListener("click", () => toggleFavorite(q.title, star));
  qText.prepend(star);

  qText.insertAdjacentHTML("beforeend", q.text);
  MathJax.typeset();

  let selectedChoice = null;

  // Render choices
  q.choices.forEach((choice, i) => {
    const btn = document.createElement("button");
    btn.innerHTML = choice;
    btn.className = "choice-btn";
    btn.addEventListener("click", () => {
      document.querySelectorAll(".choice-btn").forEach(b => b.classList.remove("selected"));
      btn.classList.add("selected");
      selectedChoice = i;
    });
    choicesDiv.appendChild(btn);
  });

  MathJax.typeset();

  // Confirm Button
  const confirmBtn = document.createElement("button");

  confirmBtn.id = "confirm-btn";
  confirmBtn.textContent = "تأكيد الإجابة";
  confirmBtn.addEventListener("click", () => {
    if (selectedChoice === null) {
      feedback.textContent = "⚠️ الرجاء اختيار إجابة أولاً.";
      feedback.style.color = "orange";
      return;
    }

    if (q.status === null) q.status = (selectedChoice === q.answer) ? "correct" : "wrong";

    // Save progress to Firebase  (;
    if (currentUser) {
      const userRef = ref(database, "users/" + currentUser.uid + "/progress");
      update(userRef, { [q.title]: q.status });
    }

    renderQuestionList();

    if (selectedChoice === q.answer) {
      feedback.textContent = "✅ إجابة صحيحة!"; feedback.style.color = "green";
      details.style.display = "block";
      details.innerHTML = `<p><strong>📘 المحور:</strong> ${q.category}</p><p><strong>🎯 المستوى:</strong> ${q.difficulty}</p>`;
      explainSection.innerHTML = "";

      document.querySelectorAll(".choice-btn").forEach(b => b.disabled = true);
      confirmBtn.disabled = true; confirmBtn.style.opacity = 0.7;

      const explainBtn = document.createElement("button");
      explainBtn.id = "explain-btn";
      explainBtn.textContent = "📘 التوضيح";
      explainBtn.addEventListener("click", () => {
        const div = document.createElement("div");
        div.id = "explain-area";
        div.innerHTML = q.explanation;
        explainSection.appendChild(div);
        MathJax.typeset();
        explainBtn.disabled = true;
      });
      explainSection.appendChild(explainBtn);

      nextBtn.style.display = "inline-block";
      nextBtn.onclick = () => {
        if (index < currentQuestions.length - 1) showQuestion(index + 1);
        else {
          feedback.textContent = "🎉 أحسنت! لقد أنهيت جميع الأسئلة.";
          choicesDiv.innerHTML = "";
          details.innerHTML = "";
          explainSection.innerHTML = "";
          nextBtn.style.display = "none";
        }
      };
    } else {
      feedback.textContent = "❌ إجابة خاطئة، حاول مرة أخرى.";
      feedback.style.color = "red";
      details.style.display = "none"; explainSection.innerHTML = "";
    }
  });

  choicesDiv.appendChild(confirmBtn);
  questionScreen.style.display = "block";
}

