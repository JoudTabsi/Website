// Render Theorems
function renderTheorems() {
  theoremContainer.innerHTML = "";
  for (const [category, items] of Object.entries(theorems)) {
    const catElem = document.createElement("div");
    catElem.className = "category";
    catElem.textContent = category;
    theoremContainer.appendChild(catElem);

    items.forEach(t => {
      const theoremDiv = document.createElement("div");
      theoremDiv.className = "theorem";
      theoremDiv.innerHTML = `
        <div class="theorem-title">
          <span>${t.title}</span>
          <span class="arrow">▼</span>
        </div>
        <div class="theorem-content">${t.content}</div>
      `;
      theoremDiv.addEventListener("click", () => toggleContent(theoremDiv));
      theoremContainer.appendChild(theoremDiv);
    });
  }

  // === Add IDs for shortcuts (AFTER they exist) ===
  document.querySelectorAll(".category").forEach(cat => {
    const text = cat.textContent.trim();
    if (text.includes("الهندسة")) cat.id = "geometry";
    else if (text.includes("الجبر")) cat.id = "algebra";
    else if (text.includes("نظرية الأعداد")) cat.id = "numbers";
    else if (text.includes("التحليل التوافقي")) cat.id = "combinatorics";
  });

  // === Enable smooth scrolling for shortcut buttons ===
  document.querySelectorAll("#theorem-shortcuts button").forEach(btn => {
    btn.addEventListener("click", () => {
      const targetId = btn.dataset.target;
      const target = document.getElementById(targetId);
      if (target) {
        const yOffset = -80; // adjust depending on the header height
        const y = target.getBoundingClientRect().top + window.pageYOffset + yOffset;
        window.scrollTo({ top: y, behavior: "smooth" });
      }
    });
  });
  MathJax.typesetPromise([theoremContainer]);
}

// Toggle content for each theorem
function toggleContent(el) {
  const content = el.querySelector(".theorem-content");
  const arrow = el.querySelector(".arrow");
  const isOpen = content.style.display === "block";
  document.querySelectorAll(".theorem-content").forEach(c => c.style.display = "none");
  document.querySelectorAll(".arrow").forEach(a => a.classList.remove("open"));
  if (!isOpen) {
    content.style.display = "block";
    arrow.classList.add("open");
  }
}

